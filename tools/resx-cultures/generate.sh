#!/usr/bin/env bash
# Generate crates/resx/src/cultures.rs, the table of .NET culture names eludite-resx uses to tell a culture file
# (`Name.de-DE.resx`) from a neutral file whose base name has a dot (`Default.aspx.resx`), proposal 0005.
#
#   tools/resx-cultures/generate.sh          # writes crates/resx/src/cultures.rs with the SDK on PATH (global.json's)
#
# The table is CultureInfo.GetCultures(CultureTypes.AllCultures) minus the invariant culture, sorted ordinally,
# as the SDK's runtime enumerates them on this machine (ICU on Linux and macOS, NLS on Windows); the file's header
# records which. The file is generated, never hand-edited: re-run this script to change it.
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
root="$(cd "$here/../.." && pwd)"
out="$root/crates/resx/src/cultures.rs"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

cat > "$work/cultures.csproj" <<'CSPROJ'
<Project Sdk="Microsoft.NET.Sdk">
  <PropertyGroup>
    <OutputType>Exe</OutputType>
    <TargetFramework>net10.0</TargetFramework>
    <Nullable>enable</Nullable>
    <ImplicitUsings>enable</ImplicitUsings>
    <InvariantGlobalization>false</InvariantGlobalization>
  </PropertyGroup>
</Project>
CSPROJ
cat > "$work/Program.cs" <<'CS'
using System.Globalization;
using System.Runtime.InteropServices;
var names = CultureInfo.GetCultures(CultureTypes.AllCultures)
    .Select(c => c.Name)
    .Where(n => n.Length > 0)
    .Distinct(StringComparer.Ordinal)
    .OrderBy(n => n, StringComparer.Ordinal)
    .ToList();
Console.WriteLine($"// {names.Count} {RuntimeInformation.FrameworkDescription} {(OperatingSystem.IsWindows() ? "NLS" : "ICU")}");
foreach (var n in names) Console.WriteLine(n);
CS
cd "$work"
dotnet run --nologo > "$work/names.txt"
header="$(head -1 "$work/names.txt")"
count="$(echo "$header" | awk '{ print $2 }')"
runtime="$(echo "$header" | cut -d' ' -f3- | sed 's/ [A-Z]*$//')"
source="$(echo "$header" | awk '{ print $NF }')"
sdk="$(dotnet --version)"
{
  echo "//! The .NET culture names (proposal 0005). Generated by \`tools/resx-cultures/generate.sh\` with SDK $sdk"
  echo "//! ($runtime, $source); $count names. Never edit by hand: re-run the script."
  echo
  echo "/// Every culture name \`CultureInfo.GetCultures(CultureTypes.AllCultures)\` returned, sorted ordinally, without"
  echo "/// the invariant culture's empty name."
  echo "pub const CULTURES: &[&str] = &["
  tail -n +2 "$work/names.txt" | sed 's/^\(.*\)$/    "\1",/'
  echo "];"
} > "$out"
echo "$out: $count cultures" >&2
